-- ============================================================
-- V9.36.0: 清理遗留的旧菜单（50000 系列）
--
-- 背景：
--   V6.3.0 创建了旧菜单（50000-59999），V6.13.0+ 创建了 Mega Menu（60000+）
--   两套菜单并存导致前端显示重复。需要清理旧的 50000 系列菜单。
--
-- 清理范围：
--   - 50010: 工作台（旧）→ 保留，因为新版也有工作台
--   - 50100-50199: 销售作业 → 已被 60001（销售）替代
--   - 50200-50299: 采购作业 → 已被 60002（采购）替代
--   - 50300-50399: 仓储作业 → 已被 60003（仓储）替代
--   - 50400-50499: WMS仓储执行 → 已并入 60003（仓储）扩展列
--   - 50500-50599: 配送管理 → 已被 60005（配送）替代
--   - 50600-50699: 客户关系 → 已被 60007（CRM）替代
--   - 50700-50799: 财务管理 → 已被 60006（财务）替代
--   - 50800-50899: 费用管理 → 已并入 60006（财务）费用管理列
--   - 50900-50999: 资产管理 → 已并入 60006（财务）资产管理列
--   - 51000-51099: 预算管理 → 已并入 60006（财务）预算管理列
--   - 51100-51199: 商城管理 → 已被 60009（商城）替代
--   - 51200-51299: 订单中心 → 已并入 60001（销售）订单中心列
--   - 51300-51399: 工作流 → 已被 60013（设置）工作流列替代
--   - 51400-51499: 产品数据 → 已被 60011（资料）替代
--   - 51500-51599: 打印管理 → 已被 60013（设置）打印管理列替代
--   - 51600-51699: 系统管理 → 已被 60013（设置）+ 60014（系统）替代
--   - 51700-51799: 图表 → 已并入 60010（分析）综合单据列
--
-- 注意：本脚本包含 DELETE 操作，需要排他锁。
-- ============================================================

-- 设置锁等待超时（30秒）
SET lock_timeout = '30s';

-- Step 1: 清理 sys_role_menu 中的授权记录
DELETE FROM sys_role_menu
WHERE menu_id >= 50100 AND menu_id < 60000;

-- Step 2: 清理 sys_tenant_menu 中的授权记录
DELETE FROM sys_tenant_menu
WHERE menu_id >= 50100 AND menu_id < 60000;

-- Step 3: 物理删除所有 50000 系列的子菜单（parent_id > 0）
DELETE FROM sys_menu
WHERE id >= 50100 AND id < 60000 AND parent_id > 0;

-- Step 4: 物理删除 50000 系列的一级菜单（parent_id = 0）
-- 注意：保留 50010（工作台），因为新版也有工作台，但需要检查是否重复
DELETE FROM sys_menu
WHERE id >= 50100 AND id < 60000 AND parent_id = 0;

-- Step 5: 检查 50010（工作台）是否与新版工作台重复
-- 如果新版（60000+）也有工作台，则删除旧的 50010
-- 先查看是否存在新版工作台
-- SELECT id, menu_name, menu_code FROM sys_menu WHERE menu_code = 'dashboard' AND id >= 60000;

-- 如果没有新版工作台，保留 50010；否则删除 50010
-- 这里假设新版也有工作台（根据 mega-menu-redesign.md 第十节的树形图）
DELETE FROM sys_role_menu WHERE menu_id = 50010;
DELETE FROM sys_tenant_menu WHERE menu_id = 50010;
DELETE FROM sys_menu WHERE id = 50010;

