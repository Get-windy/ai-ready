    code         VARCHAR(12)  NOT NULL,
    name         VARCHAR(64)  NOT NULL,
    parent_code  VARCHAR(12),
    region_level SMALLINT     NOT NULL,
    sort_order   INTEGER      DEFAULT 0,
    status       SMALLINT     DEFAULT 1,
