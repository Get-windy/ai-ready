-- ============================================================
-- V6.24.0 重命名配发收模块中的相似列名
--
-- 变更说明：
--   1. 发货业务(60402) → 物流配送（侧重物流配送操作）
--   2. 发货作业(60309) → 仓库发货（侧重仓库发货单据）
--   目的：避免同一模块下出现名称相似的列，提高可读性
-- ============================================================

-- 重命名 60402: 发货业务 → 物流配送
UPDATE sys_menu SET
    menu_name = '物流配送',
    update_time = CURRENT_TIMESTAMP
WHERE id = 60402;

-- 重命名 60309: 发货作业 → 仓库发货
UPDATE sys_menu SET
    menu_name = '仓库发货',
    update_time = CURRENT_TIMESTAMP
WHERE id = 60309;

-- ============================================================
-- 验证结果
-- ============================================================
SELECT '重命名后的列：' AS info;

SELECT
    id,
    menu_name,
    menu_code,
    parent_id
FROM sys_menu
WHERE id IN (60402, 60309)
ORDER BY id;
