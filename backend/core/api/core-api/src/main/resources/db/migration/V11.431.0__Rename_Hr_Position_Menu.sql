-- =============================================================================
-- HR 组织管理 · 菜单「职位管理」正名为「岗位编制」
-- V11.431.0 · 2026-09-20
--
-- 【为什么要改名】
--   系统里存在三套都带"岗位/职位"字样的概念，菜单名撞车导致使用者分不清：
--     ① `sys_role`（角色）—— **权限载体**，菜单挂在「职员管理 → 岗位权限」(80531，V11.429.0 已改指角色页)
--     ② `hr_position`（本菜单 90006）—— **编制单位**，带 编制人数/在岗人数/空缺/是否超编
--     ③ `sys_position`（系统岗位）—— 无菜单、无数据、无引用（`sys_user_position` 0 行且全代码库无读写入口）
--   实测（devdb 2026-09-19）：`hr_position` / `sys_position` / `sys_user_position` 真实数据均为 0 行，
--   `sys_user.post_id` 全为 NULL —— 即三套概念里**只有 sys_role 是活的**。
--   菜单 90006 名为「职位管理」，与「岗位权限」并列时极易被理解成同一件事的两种说法。
--   其真实职责是**编制管控**（对应 SAP 的 targetFTE + positionControlled、用友/金蝶的「控编方式」），
--   而 ql361 **没有**这一层（它连人资模块都没有，其"职务"只是职员档案里的自由文本）。
--   故把菜单正名为「岗位编制」：一眼即可与"岗位权限（角色）"区分。
--
-- 【本迁移只改显示名】
--   · **不改 `menu_code`（`hr:position`）** —— 它是权限码前缀（`hr:position:create/list/delete` 等
--     已在 sys_permission 中注册且可能已授给角色），改名会直接断开授权关系。
--   · 不改 path/component/parent_id/sort。
--   · 不动 `sys_position` 相关表 —— 孤儿表的清理按本仓既定流程（观察 → 改名 zz_deprecated_* → 再观察 → drop），
--     不与本迁移同批执行。
--
-- 【幂等】UPDATE 带 `deleted = 0` 条件，重复执行结果一致。
--
-- 【回滚】
--   UPDATE sys_menu SET menu_name = '职位管理', update_time = now() WHERE id = 90006;
--
-- 迁移版本号：落地前实测该目录最大为 V11.430.0，故取 V11.431.0。
-- =============================================================================

UPDATE sys_menu
SET menu_name   = '岗位编制',
    update_time = now()
WHERE id = 90006
  AND deleted = 0;
