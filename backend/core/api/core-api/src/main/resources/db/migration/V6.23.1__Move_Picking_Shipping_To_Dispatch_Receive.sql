-- ============================================================
-- PART 1: 移动列节点（二级目录）
-- ============================================================

-- 移动拣货作业(60308)到配发收(60004)下，排序值设为400（在收货业务之后）
UPDATE sys_menu SET
    parent_id = 60004,
    sort = 400,
    menu_code = 'mega:dr:picking',
    update_time = CURRENT_TIMESTAMP
WHERE id = 60308;

-- 移动发货作业(60309)到配发收(60004)下，排序值设为500
UPDATE sys_menu SET
    parent_id = 60004,
    sort = 500,
    menu_code = 'mega:dr:shipping',
    update_time = CURRENT_TIMESTAMP
WHERE id = 60309;

-- ============================================================
-- PART 2: 调整配发收原有列的排序值（为新增列腾出空间）
-- ============================================================

-- 原发货业务(60402)排序值从200调整为200（保持不变）
-- 原收货业务(60403)排序值从300调整为300（保持不变）
-- 新增的拣货作业(60308)排序值400，发货作业(60309)排序值500

-- ============================================================
-- PART 3: 验证结果
-- ============================================================
SELECT '配发收模块下的列：' AS info;

SELECT
    id,
    menu_name,
    menu_code,
    sort,
    parent_id
FROM sys_menu
WHERE parent_id = 60004 AND menu_type = 0 AND deleted = 0
ORDER BY sort;

SELECT '仓储模块下的列（应不再包含拣货作业和发货作业）：' AS info;

SELECT
    id,
    menu_name,
    menu_code,
    sort
FROM sys_menu
WHERE parent_id = 60003 AND menu_type = 0 AND deleted = 0
ORDER BY sort;
