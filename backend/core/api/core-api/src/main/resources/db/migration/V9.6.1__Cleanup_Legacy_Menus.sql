WHERE menu_id IN (500, 501, 502, 503, 700, 701, 702, 703, 704, 900, 901, 902, 903, 904, 905, 906);

-- Step 2: 物理删除子节点
DELETE FROM sys_menu
WHERE id IN (
    501, 502, 503,           -- 质量管理的子节点
    701, 702, 703, 704,       -- 支付结算的子节点
    901, 902, 903, 904, 905, 906  -- 人力资源的子节点
);

-- Step 3: 物理删除一级菜单
DELETE FROM sys_menu
WHERE id IN (500, 700, 900);

